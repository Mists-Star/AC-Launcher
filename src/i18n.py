# ---- runtime language state -------------------------------------------------
_DEFAULT_LANG = "zh-CN"
_CURRENT = _DEFAULT_LANG


def set_language(lang: str) -> None:
    """Switch the active language. Unknown codes are ignored (keeps current)."""
    global _CURRENT
    if lang in _STRINGS:
        _CURRENT = lang


def get_language() -> str:
    return _CURRENT


def available_languages() -> list[str]:
    return list(_STRINGS.keys())


def t(key: str, **kwargs) -> str:
    """Return the translated string for `key` in the active language.

    Missing keys return the key itself (a visible dev signal). Placeholders use
    {name} and are filled from kwargs via str.format (so {n:,} works too).
    """
    table = _STRINGS.get(_CURRENT, _STRINGS[_DEFAULT_LANG])
    text = table.get(key)
    if text is None:
        # fall back to default language, then to the key
        text = _STRINGS[_DEFAULT_LANG].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def loader_name(loader_id: str) -> str:
    """Localized display name for a loader id (falls back to the id itself)."""
    return LOADER_NAMES.get(loader_id, loader_id)


def version_type_name(type_id: str) -> str:
    """Localized display name for a version type id."""
    return VERSION_TYPE_NAMES.get(type_id, type_id)
